//! Circuit seams: a circuit binds a private witness to its public inputs; a
//! circuit identity pins the exact compiled artifact and verification key;
//! provers and verifiers are parameterised by the circuit so they agree on
//! both types.

use crate::codec::FromFields;
use crate::error::Error;

/// The field every circuit is compiled over (BN254 scalar field).
pub type Field = ark_bn254::Fr;

/// A circuit: the binding between the private *witness* and the *public
/// inputs* (the claim). The prover supplies both.
pub trait Circuit {
    /// The private inputs the circuit constrains (every `main` parameter).
    type Witness: FromFields;
    /// The public inputs (the claim) the circuit exposes.
    type PublicInputs;

    /// The public inputs as field elements, in circuit order: what a
    /// verifier checks the proof against.
    fn public_inputs(public: &Self::PublicInputs) -> Vec<Field>;

    /// Every ABI parameter (private and public, in `main()` declaration
    /// order, structs and arrays expanded) as field elements in ACIR
    /// witness-index order: element `i` is ACIR `Witness(i)`.
    fn witness_inputs(witness: &Self::Witness, public: &Self::PublicInputs) -> Vec<Field>;

    /// What `main` returns (through the databus, or public for a hiding
    /// kernel), typed.
    type Outputs: FromFields;
    /// Position of a top-level `vk_tree_root` among the returned fields: the
    /// key tree a hiding kernel's proof was folded under (the noir-zk kernel
    /// convention), which verifiers must check.
    const VK_TREE_ROOT_OUTPUT: Option<usize> = None;
}

/// Which proof system proves a circuit. `noir-zk freeze` reads it off the
/// ABI: a circuit using the databus is folded by Chonk (UltraHonk rejects
/// databus circuits), any other is proved on its own by UltraHonk.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum ProofSystem {
    /// A standalone UltraHonk proof, with this transcript hash.
    UltraHonk(Oracle),
    /// Folded by Chonk in this role.
    Chonk(ChonkRole),
}

/// UltraHonk's transcript hash: fixed per circuit, since its verification
/// key and proofs depend on it.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum Oracle {
    /// Poseidon2: cheap to verify inside another circuit.
    Poseidon2,
    /// Keccak: for EVM verifiers.
    Keccak,
}

impl Oracle {
    /// bb's name for it (`oracle_hash_type`).
    pub const fn name(self) -> &'static str {
        match self {
            Self::Poseidon2 => "poseidon2",
            Self::Keccak => "keccak",
        }
    }
}

/// A circuit's role in a Chonk fold (`bb write_vk --circuit_kind`).
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum ChonkRole {
    /// A step circuit, folded by the kernel after it.
    App,
    /// A kernel: folds the previous kernel and its step.
    Kernel,
    /// The final, zero-knowledge kernel whose key verifies the whole proof.
    Hiding,
}

impl ChonkRole {
    /// bb's numbering (Chonk circuit kind).
    pub const fn code(self) -> u32 {
        match self {
            Self::App => 0,
            Self::Kernel => 1,
            Self::Hiding => 2,
        }
    }
}

/// The identity of one frozen circuit version. Implemented (build-generated)
/// by every circuit marker type of a registry generated by `noir-zk-codegen`.
///
/// The bytecode isn't embedded (a circuit set easily runs to hundreds of MB):
/// it is fetched from an artifact store and must hash to
/// [`CircuitId::BYTECODE_SHA256`].
pub trait CircuitId {
    /// Circuit package name, e.g. `dsc_ecdsa_p256_sha256_tbs1000`.
    const LABEL: &'static str;
    /// Frozen version.
    const VERSION: &'static str;
    /// Which proof system proves it.
    const SYSTEM: ProofSystem;
    /// SHA-256 of the base64 bytecode string as nargo emits it: the
    /// artifact's pinned identity.
    const BYTECODE_SHA256: [u8; 32];
    /// Verification key (bb's binary encoding, for [`CircuitId::SYSTEM`]).
    const VK_BYTES: &'static [u8];
    /// SHA-256 of [`CircuitId::VK_BYTES`]: what a downloaded `.vk` file must
    /// hash to.
    const VK_SHA256: [u8; 32];
}

/// A proof-generation backend for circuit `C`.
pub trait ProofGenerator<C: Circuit> {
    /// The proof this backend produces.
    type Proof;
    /// Prove `public` for `witness`.
    fn generate(
        &self,
        witness: &C::Witness,
        public: &C::PublicInputs,
    ) -> Result<Self::Proof, Error>;
}

/// A proof-verification backend for circuit `C`.
pub trait ProofVerifier<C: Circuit> {
    /// The proof this backend verifies.
    type Proof;
    /// Verify `proof` against `public`.
    fn verify(&self, public: &C::PublicInputs, proof: &Self::Proof) -> Result<bool, Error>;
}

/// A circuit proved on its own by UltraHonk ([`ProofSystem::UltraHonk`]):
/// its proof's public inputs are its `pub` parameters, then its `pub` return
/// values.
pub trait Honk: Circuit + CircuitId {}
